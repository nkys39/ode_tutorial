// ===================================================================
// 01: Hello World - ODEの基礎
// ===================================================================
// このチュートリアルでは、ODEの最も基本的な初期化方法を学びます。
// 物理シミュレーションの基盤となる「世界」と「空間」の概念を理解しましょう。
// ===================================================================

#include "viewer.h"  // OpenGL可視化ヘルパー（カメラ操作、描画補助）
#include "utils.h"   // ユーティリティ関数（オブジェクト作成など）
#include <iostream>  // コンソール出力用

using namespace ode_tutorial;  // 名前空間を使用（ode_tutorial::を省略可能に）

// ===================================================================
// グローバル変数
// ===================================================================
// ODEの世界（World）とは？
//   物理シミュレーションが行われる仮想空間です。重力、時間の進み方、
//   物体の相互作用などがここで管理されます。
dWorldID world;

// ODEの空間（Space）とは？
//   衝突検出のための空間管理システムです。どの物体同士が接触する
//   可能性があるかを効率的に判定します。
dSpaceID space;

// ===================================================================
// シミュレーションステップ関数
// ===================================================================
// この関数は毎フレーム呼ばれます（通常60FPS = 1秒に60回）
// 引数：dt（デルタタイム） = 前フレームからの経過時間（秒）
void simulationStep(double dt) {
    // dWorldStep: 物理演算を1ステップ進める
    // 第1引数：world = シミュレーション世界
    // 第2引数：dt = 時間ステップ（秒）
    //
    // 例：dt = 0.016秒（約60FPS）なら、0.016秒分の物理演算を実行
    // この関数内で、すべての物体の位置・速度・回転が更新されます
    dWorldStep(world, dt);
}

// ===================================================================
// 描画コールバック関数
// ===================================================================
// この関数も毎フレーム呼ばれ、画面に何を描画するかを指定します
void drawScene() {
    // このチュートリアルでは何も描画しません
    // グリッドと座標軸はViewer側で自動的に描画されます

    // デバッグ用：Hello Worldメッセージを出力（毎フレーム表示される）
    // 注意：実際のアプリではこの頻度で出力すると重くなります
    std::cout << "Hello, ODE World!" << std::endl;
}

// ===================================================================
// メイン関数
// ===================================================================
int main(int argc, char** argv) {
    // ===================================================================
    // 1. 初期メッセージ表示
    // ===================================================================
    std::cout << "=== 01: Hello World ===" << std::endl;
    std::cout << "このチュートリアルでは、ODEの基本的な初期化方法を学びます。" << std::endl;
    std::cout << std::endl;
    std::cout << "操作方法:" << std::endl;
    std::cout << "  マウスドラッグ: カメラ回転" << std::endl;
    std::cout << "  マウスホイール or Z/X: ズーム" << std::endl;
    std::cout << "  矢印キー or I/J/K/L: カメラ移動" << std::endl;
    std::cout << "  スペース: 一時停止/再開" << std::endl;
    std::cout << "  R: リセット" << std::endl;
    std::cout << "  Q/ESC: 終了" << std::endl;
    std::cout << std::endl;

    // ===================================================================
    // 2. ODEの初期化
    // ===================================================================
    // dInitODE(): ODEライブラリを初期化する必須関数
    // これを呼ばないと、他のODE関数が正しく動作しません
    // プログラムの最初に1回だけ呼びます
    dInitODE();

    // ===================================================================
    // 3. 物理世界（World）の作成
    // ===================================================================
    // dWorldCreate(): 新しい物理世界を作成
    // 戻り値：dWorldID = 世界を識別するためのID（ハンドル）
    world = dWorldCreate();

    // dWorldSetGravity(): 重力を設定
    // 第1引数：world = 対象の世界
    // 第2-4引数：重力ベクトル (x, y, z) [m/s²]
    //
    // この例：(0, 0, -9.81) = Z軸の負方向に9.81m/s²
    // 地球の重力加速度は約9.81m/s²なので、現実世界と同じ設定
    //
    // 座標系：
    //   X軸：右方向（正）、左方向（負）
    //   Y軸：前方向（正）、後方向（負）
    //   Z軸：上方向（正）、下方向（負）
    dWorldSetGravity(world, 0, 0, -9.81);

    // ===================================================================
    // 4. 衝突検出空間（Space）の作成
    // ===================================================================
    // dHashSpaceCreate(): ハッシュベースの空間を作成
    // 引数：0 = デフォルト設定
    //
    // 空間の種類：
    //   - Simple Space: 総当たりで衝突判定（小規模向け）
    //   - Hash Space: ハッシュテーブルで効率化（中規模向け）
    //   - Quad Tree Space: 4分木で空間分割（大規模向け）
    //
    // このチュートリアルではHash Spaceを使用（バランスが良い）
    space = dHashSpaceCreate(0);

    // ===================================================================
    // 5. ビューワー（可視化ウィンドウ）の作成
    // ===================================================================
    // Viewer: OpenGLを使った3D可視化ウィンドウ
    // 第1-2引数：argc, argv = コマンドライン引数（GLUTが使用）
    // 第3引数：title = ウィンドウのタイトル
    Viewer viewer(argc, argv, "01: Hello World - ODE Tutorial");

    // setSimulationCallback(): シミュレーション関数を登録
    // 引数：simulationStep関数のポインタ
    // この関数が毎フレーム自動的に呼ばれます
    viewer.setSimulationCallback(simulationStep);

    // setDrawCallback(): 描画関数を登録
    // 引数：drawScene関数のポインタ
    // この関数も毎フレーム呼ばれ、画面描画を担当します
    viewer.setDrawCallback(drawScene);

    // ===================================================================
    // 6. メインループの開始
    // ===================================================================
    // start(): 可視化ループを開始
    // この関数は戻ってきません（無限ループになります）
    // ユーザーがウィンドウを閉じるまで、以下が繰り返されます：
    //   1. simulationStep()を呼ぶ → 物理演算
    //   2. drawScene()を呼ぶ → 画面描画
    //   3. ユーザー入力を処理（キーボード、マウス）
    viewer.start();

    // ===================================================================
    // 7. クリーンアップ（メモリ解放）
    // ===================================================================
    // 注意：viewer.start()は戻ってこないため、以下のコードは
    // 通常は実行されません。ただし、正しい終了処理の例として
    // 記載しています。

    // dSpaceDestroy(): 空間を破棄
    // 引数：space = 破棄する空間のID
    // 空間に登録されているすべてのジオメトリも自動的に破棄されます
    dSpaceDestroy(space);

    // dWorldDestroy(): 世界を破棄
    // 引数：world = 破棄する世界のID
    // 世界に登録されているすべての物体も自動的に破棄されます
    dWorldDestroy(world);

    // dCloseODE(): ODEライブラリを終了
    // プログラムの最後に1回だけ呼びます
    // これにより、ODEが確保していたメモリがすべて解放されます
    dCloseODE();

    return 0;  // プログラム正常終了
}
