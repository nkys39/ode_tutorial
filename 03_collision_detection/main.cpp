// ===================================================================
// 03: Collision Detection - 衝突検出と反発
// ===================================================================
// このチュートリアルでは、地面との衝突検出と反発を実装します。
// nearCallback（衝突コールバック）の仕組みを理解しましょう。
// ===================================================================

#include "viewer.h"
#include "utils.h"
#include <iostream>

using namespace ode_tutorial;

// ===================================================================
// グローバル変数
// ===================================================================
dWorldID world;  // 物理世界
dSpaceID space;  // 衝突検出空間
dBodyID sphere;  // 球の剛体
dGeomID sphere_geom;  // 球のジオメトリ
dGeomID ground_geom;  // 地面のジオメトリ

// 新しい概念：接触ジョイントグループ
//
// dJointGroupIDとは？
//   一時的なジョイント（関節）をまとめて管理するためのグループです。
//   衝突時に作成される「接触ジョイント」を効率的に管理できます。
//
// なぜ必要？
//   接触は毎フレーム変化します（物体が離れたり、新しく接触したり）
//   毎フレーム古い接触を削除し、新しい接触を作成する必要があります
//   グループを使えば、dJointGroupEmpty()で一括削除できて便利
dJointGroupID contact_group;

// 球の半径（定数として定義）
const dReal SPHERE_RADIUS = 0.2;

// ===================================================================
// 衝突コールバック関数（nearCallback）
// ===================================================================
// この関数は、2つのジオメトリが近接したときに自動的に呼ばれます
// 引数：
//   data: ユーザーデータ（今回は使用しない）
//   o1, o2: 近接している2つのジオメトリのID
//
// 重要：この関数の中で、実際に衝突しているかを詳細チェックし、
// 衝突していれば接触ジョイントを作成します
void nearCallback(void* data, dGeomID o1, dGeomID o2) {
    // ===================================================================
    // 1. 剛体の取得
    // ===================================================================
    // dGeomGetBody(): ジオメトリに関連付けられた剛体を取得
    // 戻り値：剛体ID（または0 = 剛体なし）
    //
    // 例：地面のような静的オブジェクトは剛体を持たない（geomのみ）
    dBodyID b1 = dGeomGetBody(o1);
    dBodyID b2 = dGeomGetBody(o2);

    // ===================================================================
    // 2. 除外条件のチェック
    // ===================================================================
    // dAreConnected(): 2つの剛体がジョイントで接続されているか
    // 戻り値：true = 接続されている、false = 接続されていない
    //
    // なぜこのチェックが必要？
    //   ロボットアームなど、ジョイントで接続された物体同士は
    //   意図的に接触させることがあります。その場合、接触ジョイントを
    //   作成すると動きがおかしくなるため、除外します
    //
    // この例では、どちらかが剛体を持たない（地面など）か、
    // 両方が剛体を持っていても接続されていなければ処理を続行
    if (b1 && b2 && dAreConnected(b1, b2)) return;

    // ===================================================================
    // 3. 衝突点の検出
    // ===================================================================
    // 接触点の最大数（通常は4点で十分）
    // 箱と地面の接触などでは、最大4つの角が同時に接触する可能性
    const int MAX_CONTACTS = 4;

    // dContact: 接触情報を格納する構造体
    // 各接触点について、位置、法線、深度などの情報を保持
    dContact contact[MAX_CONTACTS];

    // dCollide(): 2つのジオメトリの詳細な衝突判定
    // 引数：
    //   o1, o2: 判定する2つのジオメトリ
    //   MAX_CONTACTS: 検出する接触点の最大数
    //   &contact[0].geom: 接触情報を格納する配列の先頭アドレス
    //   sizeof(dContact): 1つの接触情報のサイズ（配列の要素間隔）
    //
    // 戻り値：n = 検出された接触点の数（0 = 衝突なし）
    int n = dCollide(o1, o2, MAX_CONTACTS, &contact[0].geom, sizeof(dContact));

    // ===================================================================
    // 4. 各接触点に対して接触ジョイントを作成
    // ===================================================================
    for (int i = 0; i < n; i++) {
        // 接触面の特性を設定
        // mode: どの物理パラメータを使用するか指定するフラグ
        contact[i].surface.mode = dContactBounce | dContactSoftCFM;
        //   dContactBounce: 反発係数を使用
        //   dContactSoftCFM: ソフト接触を使用（めり込みを許容）

        // mu（ミュー）: 摩擦係数
        // 範囲：0.0（摩擦なし、ツルツル）～ 無限大（完全に止まる）
        // 例：
        //   0.0 = 氷の上
        //   0.5 = 木と木（この例）
        //   1.0 = ゴムとコンクリート
        contact[i].surface.mu = 0.5;

        // bounce: 反発係数（弾性係数）
        // 範囲：0.0（完全非弾性、跳ねない）～ 1.0（完全弾性、エネルギー保存）
        // 例：
        //   0.0 = 粘土
        //   0.5 = テニスボール
        //   0.8 = ゴムボール（この例）
        //   0.95 = スーパーボール
        contact[i].surface.bounce = 0.8;

        // bounce_vel: 反発が起こる最小速度（m/s）
        // この速度以下での衝突では反発しない（エネルギーロスを表現）
        // 例：0.1m/s = ゆっくりぶつかったら跳ねない
        contact[i].surface.bounce_vel = 0.1;

        // soft_cfm: ソフト制約力ミキシング
        // 値が大きいほど、接触面が「柔らかく」なる（めり込みを許容）
        // 例：
        //   0.0 = 完全に硬い（めり込まない）
        //   0.01 = 少し柔らかい（この例、安定性向上）
        //   0.1 = かなり柔らかい（スポンジのよう）
        contact[i].surface.soft_cfm = 0.01;

        // ジョイントとは？
        //   2つの剛体を接続する「関節」です
        //   通常のジョイント：ヒンジ、スライダーなど（永続的）
        //   接触ジョイント：衝突時のみ作成される一時的なジョイント
        //
        // dJointCreateContact(): 接触ジョイントを作成
        // 引数：
        //   world: どの物理世界に作成するか
        //   contact_group: どのグループに追加するか（一括削除用）
        //   &contact[i]: この接触点の情報
        //
        // 戻り値：作成されたジョイントのID
        dJointID c = dJointCreateContact(world, contact_group, &contact[i]);

        // dJointAttach(): ジョイントを2つの剛体に取り付ける
        // 引数：
        //   c: ジョイントID
        //   b1, b2: 接続する2つの剛体
        //
        // 注意：どちらかがNULL（0）の場合、静的オブジェクト（地面など）
        // として扱われます
        dJointAttach(c, b1, b2);
    }
}

// ===================================================================
// リセット関数
// ===================================================================
void reset() {
    dBodySetPosition(sphere, 0, 0, 3.0);  // 3m上に配置
    dBodySetLinearVel(sphere, 0, 0, 0);   // 速度ゼロ
    dBodySetAngularVel(sphere, 0, 0, 0);  // 回転なし
}

// ===================================================================
// シミュレーションステップ関数
// ===================================================================
void simulationStep(double dt) {
    // リセット処理
    if (Viewer::shouldReset()) {
        reset();
        Viewer::setShouldReset(false);
    }

    // ===================================================================
    // 衝突検出フェーズ
    // ===================================================================
    // dSpaceCollide(): 空間内のすべてのジオメトリペアを調べる
    // 引数：
    //   space: 調べる空間
    //   0: ユーザーデータ（今回は不要なのでNULL）
    //   &nearCallback: 近接時に呼ばれるコールバック関数
    //
    // 処理の流れ：
    //   1. 空間内のすべてのジオメトリペア（2つ組）を列挙
    //   2. 各ペアが近接していればnearCallback()を呼ぶ
    //   3. nearCallback()内で詳細な衝突判定と接触ジョイント作成
    dSpaceCollide(space, 0, &nearCallback);

    // ===================================================================
    // 物理演算フェーズ
    // ===================================================================
    // dWorldStep(): 物理シミュレーションを1ステップ進める
    // この中で：
    //   1. 重力などの外力を適用
    //   2. 接触ジョイントによる力を計算
    //   3. すべての剛体の速度と位置を更新
    dWorldStep(world, dt);

    // ===================================================================
    // クリーンアップフェーズ
    // ===================================================================
    // dJointGroupEmpty(): グループ内のすべてのジョイントを削除
    //
    // なぜ毎フレーム削除？
    //   接触は動的に変化します。前フレームで接触していた物体が
    //   今フレームでは離れているかもしれません。古い接触ジョイントを
    //   残すと、誤った力が働いてしまいます。
    //
    // 処理の流れ：
    //   1. 古い接触ジョイントを全削除
    //   2. 次フレームで dSpaceCollide() が新しい接触を検出
    //   3. nearCallback() で新しい接触ジョイントを作成
    //   4. この繰り返し
    dJointGroupEmpty(contact_group);
}

// ===================================================================
// 描画コールバック関数
// ===================================================================
void drawScene() {
    // ===================================================================
    // 地面の描画
    // ===================================================================
    // dGeomPlaneGetParams(): 平面の方程式を取得
    // 平面の方程式：ax + by + cz = d
    // 引数：
    //   ground_geom: 平面のジオメトリID
    //   plane: 結果を格納する配列 [a, b, c, d]
    //
    // この例では：[0, 0, 1, 0]
    //   0*x + 0*y + 1*z = 0
    //   つまり z = 0 （XY平面）
    dVector4 plane;
    dGeomPlaneGetParams(ground_geom, plane);

    // 地面をグレーで描画
    Viewer::setColor(0.5f, 0.5f, 0.5f);
    Viewer::drawPlane(plane, plane[3], 10.0);

    // ===================================================================
    // 球の描画
    // ===================================================================
    const dReal* pos = dBodyGetPosition(sphere);  // 位置取得
    const dReal* R = dBodyGetRotation(sphere);    // 回転取得

    // 球を赤色で描画
    Viewer::setColor(0.9f, 0.3f, 0.3f);
    Viewer::drawSphere(pos, R, SPHERE_RADIUS);
}

// ===================================================================
// メイン関数
// ===================================================================
int main(int argc, char** argv) {
    std::cout << "=== 03: Collision Detection ===" << std::endl;
    std::cout << "球が地面で跳ね返るシミュレーションです。" << std::endl;
    std::cout << "衝突検出と反発の仕組みを学びます。" << std::endl;
    std::cout << std::endl;

    // ===================================================================
    // ODE初期化
    // ===================================================================
    dInitODE();

    // ===================================================================
    // 物理世界の作成
    // ===================================================================
    world = dWorldCreate();
    dWorldSetGravity(world, 0, 0, -9.81);  // 地球の重力

    // ===================================================================
    // 衝突検出空間の作成
    // ===================================================================
    // 今回初めて実際に使用します
    space = dHashSpaceCreate(0);

    // ===================================================================
    // 接触ジョイントグループの作成
    // ===================================================================
    // dJointGroupCreate(): 新しいジョイントグループを作成
    // 引数：0 = デフォルトサイズ
    //
    // このグループは、衝突時に作成される一時的なジョイントを
    // まとめて管理するために使用します
    contact_group = dJointGroupCreate(0);

    // ===================================================================
    // 地面平面の作成
    // ===================================================================
    // dCreatePlane(): 無限平面を作成
    // 引数：
    //   space: どの空間に追加するか
    //   a, b, c: 平面の法線ベクトル (a, b, c)
    //   d: 原点からの距離
    //
    // 平面の方程式：ax + by + cz = d
    //
    // この例：(0, 0, 1, 0)
    //   0*x + 0*y + 1*z = 0
    //   つまり z = 0
    //   法線が(0,0,1)なので、Z軸に垂直な平面 = XY平面
    //
    // 注意：平面は無限に広がっており、剛体を持ちません（静的）
    ground_geom = dCreatePlane(space, 0, 0, 1, 0);

    // ===================================================================
    // 球の作成
    // ===================================================================
    // 3m上から落下させます
    sphere = createSphere(world, space, 0, 0, 3.0, SPHERE_RADIUS, 1.0, &sphere_geom);

    // ===================================================================
    // ビューワーの作成
    // ===================================================================
    Viewer viewer(argc, argv, "03: Collision Detection - ODE Tutorial");
    viewer.setSimulationCallback(simulationStep);
    viewer.setDrawCallback(drawScene);

    // ===================================================================
    // メインループ開始
    // ===================================================================
    // 毎フレーム以下が実行されます：
    //   1. dSpaceCollide() で衝突検出
    //   2. nearCallback() で接触ジョイント作成
    //   3. dWorldStep() で物理演算（重力+接触力）
    //   4. dJointGroupEmpty() で接触ジョイント削除
    //   5. 画面描画
    viewer.start();

    // ===================================================================
    // クリーンアップ
    // ===================================================================
    dBodyDestroy(sphere);  // 剛体を破棄（関連するgeomも自動破棄）

    // dGeomDestroy(): ジオメトリを破棄
    // 地面は剛体を持たないため、明示的に破棄が必要
    dGeomDestroy(ground_geom);

    // dJointGroupDestroy(): ジョイントグループを破棄
    // グループ内のすべてのジョイントも自動的に破棄されます
    dJointGroupDestroy(contact_group);

    dSpaceDestroy(space);
    dWorldDestroy(world);
    dCloseODE();

    return 0;
}
