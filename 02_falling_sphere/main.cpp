// ===================================================================
// 02: Falling Sphere - 重力による落下
// ===================================================================
// このチュートリアルでは、重力の影響を受けて落下する球体を作成します。
// 物理オブジェクトの基本概念（Body と Geom）を理解しましょう。
// ===================================================================

#include "viewer.h"  // OpenGL可視化ヘルパー
#include "utils.h"   // ユーティリティ関数（createSphere など）
#include <iostream>

using namespace ode_tutorial;

// ===================================================================
// グローバル変数
// ===================================================================
dWorldID world;  // 物理世界（前回と同じ）
dSpaceID space;  // 衝突検出空間（前回と同じ）

// 新しい概念：剛体（Body）とジオメトリ（Geom）
//
// dBodyID（剛体）とは？
//   質量、速度、力など、物理的性質を持つオブジェクトです。
//   「目に見えない質点」のようなもので、物理演算の対象となります。
//
// dGeomID（ジオメトリ）とは？
//   形状を表すオブジェクトです。球、箱、円柱などの「見た目」を定義します。
//   衝突検出にも使用されます。
//
// なぜ分かれている？
//   - Bodyなし、Geomのみ：静的な障害物（動かない壁など）
//   - BodyとGeom両方：動的なオブジェクト（落下する球など）
//   - この柔軟性により、効率的なシミュレーションが可能
dBodyID sphere;       // 球の剛体（物理的性質）
dGeomID sphere_geom;  // 球のジオメトリ（形状）

// ===================================================================
// リセット関数
// ===================================================================
// 球を初期位置に戻し、速度をゼロにします
void reset() {
    // dBodySetPosition(): 剛体の位置を設定
    // 引数：body, x, y, z（メートル単位）
    // この例：(0, 0, 3.0) = 原点の3メートル上に配置
    dBodySetPosition(sphere, 0, 0, 3.0);

    // dBodySetLinearVel(): 直線速度を設定
    // 引数：body, vx, vy, vz（メートル/秒）
    // この例：(0, 0, 0) = 静止状態（速度ゼロ）
    dBodySetLinearVel(sphere, 0, 0, 0);

    // dBodySetAngularVel(): 角速度（回転速度）を設定
    // 引数：body, wx, wy, wz（ラジアン/秒）
    // この例：(0, 0, 0) = 回転なし
    dBodySetAngularVel(sphere, 0, 0, 0);
}

// ===================================================================
// シミュレーションステップ関数
// ===================================================================
void simulationStep(double dt) {
    // Rキーが押されたかチェック
    if (Viewer::shouldReset()) {
        reset();  // 球をリセット
        Viewer::setShouldReset(false);  // フラグをクリア
    }

    // 物理演算を1ステップ進める
    // この中で重力が球に作用し、位置と速度が更新されます
    dWorldStep(world, dt);

    // dBodyGetPosition(): 剛体の現在位置を取得
    // 戻り値：dReal配列へのポインタ [x, y, z]
    //
    // なぜポインタ？
    //   ODEは内部で配列を管理しており、それへのポインタを返します。
    //   コピーではないので高速ですが、値を変更してはいけません。
    const dReal* pos = dBodyGetPosition(sphere);

    // デバッグ出力：高さを0.5m間隔で表示
    // pos[0] = X座標, pos[1] = Y座標, pos[2] = Z座標（高さ）
    //
    // トリック：pos[2] * 100 を整数化し、50で割った余りが0のとき
    // → 0.5m間隔で出力（毎フレーム出力すると重いため）
    if ((int)(pos[2] * 100) % 50 == 0) {
        std::cout << "球の高さ: " << pos[2] << " m" << std::endl;
    }
}

// ===================================================================
// 描画コールバック関数
// ===================================================================
void drawScene() {
    // 球の現在位置を取得
    const dReal* pos = dBodyGetPosition(sphere);

    // dBodyGetRotation(): 剛体の回転行列を取得
    // 戻り値：3x3回転行列（12要素の配列）
    // この情報を使って、正しい向きで描画できます
    const dReal* R = dBodyGetRotation(sphere);

    // dGeomSphereGetRadius(): 球の半径を取得
    // 引数：sphere_geom = 球のジオメトリ
    // 戻り値：半径（メートル）
    dReal radius = dGeomSphereGetRadius(sphere_geom);

    // Viewer::setColor(): 描画色を設定（RGB、0.0～1.0）
    // この例：(0.2, 0.6, 0.9) = 明るい青色
    Viewer::setColor(0.2f, 0.6f, 0.9f);

    // Viewer::drawSphere(): 球を描画
    // 引数：position（位置）, rotation（回転）, radius（半径）
    Viewer::drawSphere(pos, R, radius);
}

// ===================================================================
// メイン関数
// ===================================================================
int main(int argc, char** argv) {
    std::cout << "=== 02: Falling Sphere ===" << std::endl;
    std::cout << "重力の影響を受けて落下する球体のシミュレーションです。" << std::endl;
    std::cout << "球が落下していく様子を観察してください。" << std::endl;
    std::cout << "※ 地面がないため、球は無限に落ち続けます" << std::endl;
    std::cout << std::endl;

    // ===================================================================
    // ODEの初期化（前回と同じ）
    // ===================================================================
    dInitODE();

    // ===================================================================
    // 物理世界の作成
    // ===================================================================
    world = dWorldCreate();

    // 重力設定：Z軸負方向に9.81m/s²（地球と同じ）
    dWorldSetGravity(world, 0, 0, -9.81);

    // ===================================================================
    // 衝突検出空間の作成
    // ===================================================================
    // この時点では衝突検出は使いませんが、後のチュートリアルで必要になります
    space = dHashSpaceCreate(0);

    // ===================================================================
    // 球の作成
    // ===================================================================
    // createSphere(): ユーティリティ関数で球を作成
    // 引数の意味：
    //   world: どの物理世界に追加するか
    //   space: どの衝突検出空間に追加するか
    //   x, y, z: 初期位置（メートル）
    //     この例：(0, 0, 3.0) = 原点の3m上
    //   radius: 半径（メートル）
    //     この例：0.2m = 直径40cmの球
    //   mass: 質量（キログラム）
    //     この例：1.0kg
    //   geom_out: ジオメトリIDを格納する変数へのポインタ
    //     作成されたジオメトリIDがここに書き込まれます
    //
    // 戻り値：作成された剛体のID（dBodyID）
    //
    // この関数の内部では以下の処理が行われます：
    //   1. 剛体（Body）を作成
    //   2. 質量を設定（球の慣性モーメントも自動計算）
    //   3. ジオメトリ（Geom）を作成し、剛体に関連付け
    //   4. 初期位置を設定
    sphere = createSphere(world, space, 0, 0, 3.0, 0.2, 1.0, &sphere_geom);

    // ===================================================================
    // ビューワーの作成と設定
    // ===================================================================
    Viewer viewer(argc, argv, "02: Falling Sphere - ODE Tutorial");
    viewer.setSimulationCallback(simulationStep);
    viewer.setDrawCallback(drawScene);

    // ===================================================================
    // メインループ開始
    // ===================================================================
    // ここで無限ループに入ります
    // 毎フレーム以下が実行されます：
    //   1. 重力が球に作用
    //   2. 球の速度と位置が更新
    //   3. 球が画面に描画される
    viewer.start();

    // ===================================================================
    // クリーンアップ
    // ===================================================================
    // dBodyDestroy(): 剛体を破棄
    // 注意：剛体を破棄すると、関連付けられたジオメトリも
    // 自動的に破棄されます（明示的にdGeomDestroy()を呼ぶ必要なし）
    dBodyDestroy(sphere);

    dSpaceDestroy(space);
    dWorldDestroy(world);
    dCloseODE();

    return 0;
}
